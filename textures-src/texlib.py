def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def rgb2hex(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(round(v)))) for v in c[:3])

def ramp(name, n):
    """Smooth n-step ramp through a palette's stops (list of rgb tuples)."""
    stops = [hex2rgb(s) for s in PALETTES[name]]
    out = []
    for i in range(n):
        t = i / (n - 1) * (len(stops) - 1)
        k = min(int(t), len(stops) - 2)
        f = t - k
        out.append(tuple(stops[k][j] + (stops[k + 1][j] - stops[k][j]) * f for j in range(3)))
    return out

# ---- tileable value noise ----
class Noise:
    def __init__(self, seed, period):
        r = random.Random(seed)
        self.p = period
        self.v = [[r.random() for _ in range(period)] for _ in range(period)]

    def at(self, x, y):
        p = self.p
        x0, y0 = int(math.floor(x)) % p, int(math.floor(y)) % p
        fx, fy = x - math.floor(x), y - math.floor(y)
        fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
        x1, y1 = (x0 + 1) % p, (y0 + 1) % p
        a = self.v[y0][x0] + (self.v[y0][x1] - self.v[y0][x0]) * fx
        b = self.v[y1][x0] + (self.v[y1][x1] - self.v[y1][x0]) * fx
        return a + (b - a) * fy

def write_px(path, name, ramp_name, steps, grid, comment, layers_extra=""):
    """Write a .px script: one ramp, digits/letters in the grid index into it ('.' = transparent)."""
    keys = "0123456789abcdefghij"
    lines = [f"// {comment}", f"// Generated by {os.path.basename(path_of_caller())}; edit the generator, not this file.",
             f"size {len(grid[0])} {len(grid)}",
             f"gradramp {name} {steps} " + " ".join(PALETTES[ramp_name])]
    for i in range(steps):
        lines.append(f"key {keys[i]} {name}.{i}")
    lines.append("layer base")
    lines.append("grid 0 0")
    for row in grid:
        lines.append("".join("." if v is None else keys[v] for v in row))
    lines.append("end")
    if layers_extra:
        lines.append(layers_extra)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")

_caller = [None]
def path_of_caller():
    import inspect
    for fr in inspect.stack():
        if fr.filename.endswith(".py") and "gen_" in os.path.basename(fr.filename):
            return fr.filename
    return "gen"

def write_png(path, pixels, w, h):
    """pixels: list of rows of (r,g,b,a)."""
    raw = b"".join(b"\0" + b"".join(struct.pack("BBBB", *[max(0, min(255, int(round(c)))) for c in p]) for p in row) for row in pixels)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(png)

def write_px_multi(path, comment, ramps, grid):
    """Like write_px but cells are (palette_name, index) tuples or None; ramps = {palette_name: steps}."""
    chars = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!@$%^&*+=?<>"
    used = sorted({c for row in grid for c in row if c is not None})
    keymap = {c: chars[i] for i, c in enumerate(used)}
    lines = [f"// {comment}", f"// Generated by {os.path.basename(path_of_caller())}; edit the generator, not this file.",
             f"size {len(grid[0])} {len(grid)}"]
    for name, steps in ramps.items():
        lines.append(f"gradramp {name} {steps} " + " ".join(PALETTES[name]))
    for (name, i), ch in keymap.items():
        lines.append(f"key {ch} {name}.{i}")
    lines += ["layer base", "grid 0 0"]
    for row in grid:
        lines.append("".join("." if c is None else keymap[c] for c in row))
    lines.append("end")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
