def hanging_strands(name, mat_strand, mat_leaf, beads=None, seed=1):
    """Vertically tiling hanging plant: 2-3 wiggling strands whose x at row 0 equals row 16."""
    r = random.Random(seed)
    g = [["."] * 16 for _ in range(16)]
    paths = {
        0: [4, 4, 5, 5, 5, 4, 4, 3, 3, 4, 4, 5, 5, 5, 4, 4],
        1: [10, 10, 11, 11, 10, 10, 9, 9, 10, 10, 11, 11, 11, 10, 10, 10],
    }
    if beads: paths[2] = [7, 7, 7, 8, 8, 8, 7, 7, 7, 7, 8, 8, 8, 7, 7, 7]
    for k, p in paths.items():
        for y, x in enumerate(p):
            g[y][x] = "v"
            if beads and (y + k * 3) % 5 == 0: g[y][x] = "o"
        for y in range(1 if k else 0, 16, 3):
            x = p[y]
            d = -1 if (y // 3 + k) % 2 else 1
            g[y][x + d] = "l"
            if y + 1 < 16: g[y + 1][x + d] = "l" if not beads else "."
    mats = {"v": mat_strand, "l": mat_leaf}
    if beads: mats["o"] = beads
    return mats, "\n" + "\n".join("".join(row) for row in g)

SPRITES["weepvine"] = hanging_strands("weepvine", "vine", "leaf")
SPRITES["glowmoss_curtain"] = hanging_strands("glowmoss_curtain", "moss", "moss", beads="glowbead", seed=4)

def driftmoss():
    """Tiling moss carpet floating on water: mostly covered, with ragged holes."""
    n = Noise(21, 8)
    rows = []
    for y in range(16):
        rows.append("".join("m" if n.at(x / 2.0, y / 2.0) > 0.34 else "." for x in range(16)))
    return {"m": "moss"}, "\n" + "\n".join(rows)
SPRITES["driftmoss"] = driftmoss()

def write(name, mats, art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    out = [f"// {name}: generated by gen_plants.py; edit the grid there.", "size 16 16"]
    for ch, mat in mats.items():
        out.append(f"gradramp {mat}_{ord(ch)} 10 " + " ".join(M[mat][0]))
    for ch, mat in mats.items():
        out.append(f"layer {mat}_{ord(ch)}")
        out.append(f"key {ch} #ffffff")
        out.append("grid 0 0")
        for r in rows:
            out.append("".join(c if c == ch else "." for c in r))
        out.append("end")
        out.append(f"shade {mat}_{ord(ch)} {M[mat][1]}")
    with open(os.path.join(HERE, f"{name}.px"), "w") as f:
        f.write("\n".join(out) + "\n")

if __name__ == "__main__":
    for name, (mats, art) in SPRITES.items():
        write(name, mats, art)
