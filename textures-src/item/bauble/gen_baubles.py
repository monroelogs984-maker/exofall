"""Writes the six bauble sprites' .px scripts (32x32). Shapes are drawn here as masks (ellipses, polygons, lines),
one character per material; the .px then shades each material on its own layer and outlines the whole."""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N = 32


class Canvas:
    def __init__(self):
        self.g = [["." for _ in range(N)] for _ in range(N)]

    def put(self, x, y, ch):
        if 0 <= x < N and 0 <= y < N:
            self.g[y][x] = ch

    def ellipse(self, cx, cy, rx, ry, ch):
        for y in range(N):
            for x in range(N):
                if ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1:
                    self.put(x, y, ch)

    def ring(self, cx, cy, rx, ry, t, ch):
        for y in range(N):
            for x in range(N):
                d = ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2
                di = ((x + 0.5 - cx) / max(0.1, rx - t)) ** 2 + ((y + 0.5 - cy) / max(0.1, ry - t)) ** 2
                if d <= 1 and di > 1:
                    self.put(x, y, ch)

    def poly(self, pts, ch):
        for y in range(N):
            for x in range(N):
                px, py = x + 0.5, y + 0.5
                inside = False
                j = len(pts) - 1
                for i in range(len(pts)):
                    xi, yi = pts[i]
                    xj, yj = pts[j]
                    if (yi > py) != (yj > py) and px < (xj - xi) * (py - yi) / (yj - yi) + xi:
                        inside = not inside
                    j = i
                if inside:
                    self.put(x, y, ch)

    def rect(self, x, y, w, h, ch):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.put(xx, yy, ch)

    def line(self, x0, y0, x1, y1, ch, w=1):
        n = int(max(abs(x1 - x0), abs(y1 - y0)) * 2) + 1
        for i in range(n + 1):
            t = i / n
            x, y = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
            for dx in range(w):
                for dy in range(w):
                    self.put(int(round(x)) + dx, int(round(y)) + dy, ch)

    def mirror(self):
        for y in range(N):
            for x in range(N // 2):
                if self.g[y][x] != ".":
                    self.g[y][N - 1 - x] = self.g[y][x]

    def chain(self, x0, y0, x1, y1, ch):
        """Alternating links along a line: 2 px on, 1 px off."""
        n = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
        for i in range(n):
            if i % 3 == 2:
                continue
            t = i / max(1, n - 1)
            self.put(int(round(x0 + (x1 - x0) * t)), int(round(y0 + (y1 - y0) * t)), ch)


def write(name, canvas, ramps, layers, outline, extra=""):
    lines = ["size 32 32", f"// generated by gen_baubles.py; edit there"]
    for rname, spec in ramps.items():
        lines.append(f"gradramp {rname} {spec}")
    lines.append("layer outline")
    lines.append("layer base")
    keys = {}
    for ch, rname, _ in layers:
        keys[ch] = f"{rname}.4"
        lines.append(f"key {ch} {rname}.4")
    lines.append("grid 0 0")
    lines += ["".join(r) for r in canvas.g]
    lines.append("end")
    for ch, rname, sh in layers:
        lines += [f"layer m_{ch}", f"take base {keys[ch]}" if False else f"take base {{{ch}}}", f"shade {rname} {sh}"]
    lines += ["layer outline"] + [f"copy m_{ch}" for ch, _, _ in layers] + [f"outline {outline} outer"]
    body = "\n".join(lines) + "\n" + extra
    open(os.path.join(HERE, name + ".px"), "w").write(body)
    return body


