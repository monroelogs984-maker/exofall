"""Writes crustbreaker.px (32x32): the curved geometry is easier to compute than to type. Run by build_textures.py."""
import math, os
W = 32
HERE = os.path.dirname(os.path.abspath(__file__))

def bez(t, p0, p1, p2):
    return tuple((1 - t) ** 2 * a + 2 * (1 - t) * t * b + t * t * c for a, b, c in zip(p0, p1, p2))

P0, P1, P2 = (5.5, 8.5), (25.0, 1.0), (28.5, 26.0)
def width(t):  # blunt hammer face at t=0, thick middle, a spike at t=1
    if t < 0.08:
        return 5.6                      # square hammer face
    return 5.6 + 1.0 * min(1, (t - 0.08) / 0.4) if t < 0.5 else 6.6 - 5.4 * ((t - 0.5) / 0.5) ** 1.1

head, core, edge, band = set(), set(), set(), set()
for i in range(400):
    t = i / 399
    cx, cy = bez(t, P0, P1, P2)
    # normal
    a, b = bez(min(1, t + 0.002), P0, P1, P2), bez(max(0, t - 0.002), P0, P1, P2)
    tx, ty = a[0] - b[0], a[1] - b[1]
    L = math.hypot(tx, ty)
    nx, ny = -ty / L, tx / L          # points to the inner (lower-left) side of the arc
    w = width(t)
    for k in range(-20, 21):
        s = k / 20 * w / 2
        x, y = int(math.floor(cx + nx * s)), int(math.floor(cy + ny * s))
        if 0 <= x < W and 0 <= y < W:
            head.add((x, y))
            if s > w / 2 - 1.0 and 0.3 < t < 0.7:
                core.add((x, y))          # iron backing on the inner curve
            if s < -w / 2 + 0.9:
                edge.add((x, y))          # outer edge: the sheen line
            if 0.09 < t < 0.13:
                band.add((x, y))          # iron band capping the hammer face

handle, wrap = set(), set()
x0, y0, x1, y1 = 4.0, 28.0, 19.5, 12.5
for i in range(300):
    t = i / 299
    cx, cy = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
    for dx in (-1, 0, 1):
        for dy in (-1, 0, 1):
            if True:
                p = (int(round(cx + dx * 0.75)), int(round(cy + dy * 0.75)))
                handle.add(p)
                if 0.15 < t < 0.75 and int(t * 22) % 3 == 0:
                    wrap.add(p)
collar = {(x, y) for x in range(16, 24) for y in range(8, 16) if abs(x - 19.5) + abs(y - 11.5) <= 3.6}
gem = {(19, 11), (20, 11), (19, 12), (20, 12)}
pommel = {(x, y) for x in range(1, 6) for y in range(26, 31) if abs(x - 3) + abs(y - 28.5) <= 2.2}

def grid(cells, ch):
    rows = []
    for y in range(W):
        rows.append("".join(ch if (x, y) in cells else "." for x in range(W)))
    return "\n".join(rows)

handle -= collar
pommel_cells = pommel - collar
head_only = head - collar
out = f"""size 32 32
// Crustbreaker (generated by gen_crustbreaker.py): the meteoric pick that breaks Shellrock. A heavy curved head of
// pearl Shellrock with an oil-slick sheen along its back, a dark iron backing on the inner curve, a blunt crust
// hammer on one end and a spike on the other; an iron collar set with an echo-shard gem; a wrapped dark handle.
gradramp pearl 10 #4a4660 #6e6a86 #9c97ab #c4c0cf #e2dfe8 #f4f2f6 #fffdf8
gradramp iron 7 #0e0c14 #1c1826 #2c2638 #403a50 #5a5470
gradramp grip 7 #0c0a0c #181216 #261e22 #3a3034 #524548
gradramp lthr 5 #2a1420 #4a2436 #6e3a50 #8e5468
gradramp gem 6 #0a3b44 #0f6e7a #34b6b8 #7ae0dc #d0fff6
color pink #f2c6e6
color cyan #b6eef2
color gold #f6e6b0
layer handle
key X #261e22
grid 0 0
{grid(handle, 'X')}
end
shade grip light=-1,-1 depth=1 contrast=0.7 base=0.5
layer wrap
key L #4a2436
grid 0 0
{grid(wrap - collar, 'L')}
end
shade lthr light=-1,-1 depth=1 contrast=0.6 base=0.55
layer pommel
key P #2c2638
grid 0 0
{grid(pommel_cells, 'P')}
end
shade iron light=-1,-1 depth=2 contrast=0.7 base=0.55
layer head
key H #c4c0cf
grid 0 0
{grid(head_only, 'H')}
end
shade pearl light=-1,-1 depth=3 contrast=0.65 base=0.55 grad=28,26,12,4,0.25
layer core
key C #2c2638
grid 0 0
{grid(core - collar, 'C')}
end
shade iron light=-1,-1 depth=1 contrast=0.6 base=0.5
layer sheen
"""
# iridescent sheen: pink / white / cyan bands along the outer edge
for (x, y) in sorted(edge - collar):
    k = (x * 7 + y * 13) % 9
    col = "pink" if k == 0 else "cyan" if k == 4 else "pearl.6" if k % 2 else "pearl.5"
    out += f"px {x} {y} {col}\n"
out += f"""layer band
key B #2c2638
grid 0 0
{grid(band - collar, 'B')}
end
shade iron light=-1,-1 depth=1 contrast=0.6 base=0.55
layer collar
key K #403a50
grid 0 0
{grid(collar, 'K')}
end
shade iron light=-1,-1 depth=2 contrast=0.75 base=0.6
outline iron.0 inner
layer gem
key G #34b6b8
grid 0 0
{grid(gem, 'G')}
end
shade gem light=-1,-1 depth=1 contrast=0.6 base=0.6
px 19 11 gem.5
layer ol
copy handle
copy wrap
copy pommel
copy head
copy core
copy band
copy sheen
copy collar
copy gem
outline #0a0810 outer
mask ol
"""
open(os.path.join(HERE, "crustbreaker.px"), "w").write(out)
