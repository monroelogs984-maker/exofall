for name, (outline, layers) in SPRITES.items():
    lines = ["size 32 32", f"// generated by gen_weapon_px.py from {name}_ids.png; hand touches in {name}.fix"]
    for mat, _, ramp, _ in layers:
        lines.append(f"gradramp {mat} {ramp}")
    lines += ["layer outline", "layer ids", f"import {name}_ids.png 0 0"]
    for mat, key, _, sh in layers:
        lines += [f"layer {mat}", f"take ids {key}", f"shade {mat} {sh}"]
    lines += ["layer outline"]
    for mat, *_ in layers:
        lines.append(f"copy {mat}")
    lines += [f"outline {outline} outer"]
    fix = os.path.join(HERE, name + ".fix")
    body = "\n".join(lines) + "\n"
    if os.path.exists(fix):
        body += open(fix).read()
    with open(os.path.join(HERE, name + ".px"), "w") as fh:
        fh.write(body)
