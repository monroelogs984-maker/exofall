#!/usr/bin/env python3
"""Writes and builds the four meteor sigils and three sigil fragments (16x16 items).

One shared tablet (cool violet meteor stone, raised rim) with a glowing emblem per meteor:
swamp = water drop, hive = comb cell, desert = venom fangs, rainforest = mantis blade.
A fragment is the sigil's upper-left part with a jagged broken edge.
    python3 gen_sigils.py
"""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'src', 'main', 'resources', 'assets', 'exofall', 'textures', 'item')
PX = os.path.expanduser('~/.claude/skills/pixelart/scripts/px.py')

TABLET = [
    '................',
    '.....SSSSSS.....',
    '...SSSSSSSSSS...',
    '..SSSSSSSSSSSS..',
    '..SSSSSSSSSSSS..',
    '.SSSSSSSSSSSSSS.',
    '.SSSSSSSSSSSSSS.',
    '.SSSSSSSSSSSSSS.',
    '.SSSSSSSSSSSSSS.',
    '.SSSSSSSSSSSSSS.',
    '.SSSSSSSSSSSSSS.',
    '..SSSSSSSSSSSS..',
    '..SSSSSSSSSSSS..',
    '...SSSSSSSSSS...',
    '.....SSSSSS.....',
    '................',
]
# broken edge for the fragments: keep pixels above/left of this jagged line
def kept(x, y):
    edge = [10, 10, 9, 10, 9, 8, 8, 7, 8, 6, 5, 4, 4, 3, 2, 2]   # max x kept per row
    return x <= edge[y] - (1 if y > 8 else 0) and y <= 11

EMBLEMS = {
    'swamp': ('#5ad8c0', ['...E...', '...E...', '..EEE..', '.EEEEE.', '.EE.EEE', '.EEEEE.', '..EEE..']),
    'hive': ('#ffc040', ['..EEE..', '.E...E.', 'E..E..E', 'E.EEE.E', 'E..E..E', '.E...E.', '..EEE..']),
    'desert': ('#ff6a3a', ['E.....E', 'E.....E', 'EE...EE', '.EE.EE.', '..E.E..', '.......', '...E...']),
    'rainforest': ('#9ae04a', ['....EEE', '...EEEE', '..EEEE.', '.EEEE..', '.EEE...', 'EE.....', 'E......']),
}

def script(kind, fragment):
    colour, emb = EMBLEMS[kind]
    rows = [''.join(c if c == '.' or not fragment or kept(x, y) else '.' for x, c in enumerate(r)) for y, r in enumerate(TABLET)]
    L = ['size 16 16', f'// {kind} sigil{" fragment" if fragment else ""}: generated by gen_sigils.py',
         'gradramp st 9 #352e46 #4a4262 #6a6084 #9488ae #c0b6d6',
         f'gradramp gl 7 {colour}66 {colour} #ffffff',
         'layer stone', 'key S #6a6084', 'grid 0 0', *rows, 'end',
         'shade st light=-1,-1 depth=3 contrast=0.55 base=0.5',
         'outline st.0 inner',
         # carved groove around the emblem
         'layer groove', 'key G #4a4262', 'grid 3 3',
         '..GGGGGG..'[:10], '.G......G.', 'G........G', 'G........G', 'G........G', 'G........G', 'G........G', 'G........G', '.G......G.', '..GGGGGG..', 'end']
    L += ['layer emblem', 'key E ' + colour, 'grid 4 4', *emb, 'end',
          'shade gl light=0,0 depth=2 contrast=0.6 base=0.55']
    if fragment:
        L += ['layer groove', *[f'erase {x} {y}' for y in range(16) for x in range(16) if not kept(x, y)],
              'layer emblem', *[f'erase {x} {y}' for y in range(16) for x in range(16) if not kept(x, y)]]
    return '\n'.join(L) + '\n'

for kind in EMBLEMS:
    for frag in (False, True):
        if frag and kind == 'desert':
            continue
        name = f'{kind}_sigil{"_fragment" if frag else ""}'
        p = os.path.join(HERE, name + '.px')
        open(p, 'w').write(script(kind, frag))
        subprocess.run([sys.executable, PX, 'build', p, os.path.join(OUT, name + '.png')], check=True)
print('built')
